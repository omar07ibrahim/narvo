/** Build the response pack (Markdown) from the live workspace state — client-safe. */

import type { BidSeed, BidState } from "./types";
import { readiness, fmt } from "./compliance";

const STATUS: Record<string, string> = { met: "Evidenced", partial: "Partial", missing: "Missing" };

export function buildResponsePack(seed: BidSeed, state: BidState): string {
  const r = readiness(seed, state);
  const reqs = state.requirements?.items ?? [];
  const lines: string[] = [];
  const approved = state.bid.status === "approved_for_submission";
  lines.push(`# Response Pack — ${seed.tender.ref}`);
  lines.push("");
  lines.push(`**${seed.tender.title.en}**  `);
  lines.push(`Bidder: ${seed.bidder.name} (licence ${seed.bidder.licence}, supplier no. ${seed.bidder.supplierNo})  `);
  lines.push(`Client: ${seed.tender.client.en}  `);
  lines.push(`Closing: ${fmt(seed.tender.closing)} ${seed.tender.closingTime} via ${seed.tender.portal}  `);
  lines.push(`Status: **${approved ? `APPROVED FOR SUBMISSION by ${state.bid.approvedBy ?? "Leena Mattar"}` : "IN PREPARATION — not yet approved"}**`);
  lines.push("");
  lines.push("## Readiness summary");
  lines.push("");
  lines.push(`| Measure | Value |\n|---|---|`);
  lines.push(`| Requirement coverage | ${r.cov.pct}% evidenced (${r.cov.met}/${r.cov.total}); ${r.cov.partial} partial; ${r.cov.missing} missing |`);
  lines.push(`| Sections drafted | ${r.drafted}/${seed.sections.length} |`);
  lines.push(`| Unsupported claims (latest check) | ${r.claims.flagged} |`);
  lines.push(`| Critical compliance flags | ${r.critical} |`);
  lines.push(`| Open contributor tasks | ${r.openTasks} |`);
  lines.push("");

  for (const s of seed.sections) {
    const latest = state.sections[s.id]?.versions.at(-1);
    lines.push(`## ${s.no}. ${s.title.en}`);
    lines.push("");
    if (!latest) {
      lines.push("_Not drafted._");
      lines.push("");
      continue;
    }
    lines.push(`_${latest.label} · ${latest.author} · page limit ${s.pageLimit}_`);
    lines.push("");
    lines.push(latest.text.trim());
    lines.push("");
    const used = new Set(Array.from(latest.text.matchAll(/\[(\d+)\]/g)).map((m) => Number(m[1])));
    const cites = (latest.citations ?? []).filter((c) => used.has(c.n));
    if (cites.length) {
      lines.push("**Sources**");
      lines.push("");
      for (const c of cites) lines.push(`- [${c.n}] ${c.title}${c.ref ? ` (${c.ref})` : ""} — § ${c.section}`);
      lines.push("");
    }
  }

  lines.push("## 10. Compliance matrix");
  lines.push("");
  lines.push("| Code | Requirement | Status | Evidence | Gap / note |\n|---|---|---|---|---|");
  for (const q of reqs) {
    const c = state.coverage[q.id];
    const ev = c?.evidence[0] ? `${c.evidence[0].title}${c.evidence[0].ref ? ` (${c.evidence[0].ref})` : ""}` : "—";
    const note = (c?.gap ?? c?.check?.note ?? "").replace(/\|/g, "/");
    lines.push(`| ${q.id} | ${q.title.replace(/\|/g, "/")} | ${c ? STATUS[c.status] : "Not mapped"} | ${ev.replace(/\|/g, "/")} | ${note} |`);
  }
  lines.push("");

  lines.push("## Certificates & policies");
  lines.push("");
  lines.push("| Document | Number | Expiry | Check |\n|---|---|---|---|");
  for (const c of r.certs) lines.push(`| ${c.cert.name} | ${c.cert.number} | ${fmt(c.cert.expiry)} | ${c.status.toUpperCase()} — ${c.note.en} |`);
  lines.push("");
  lines.push("## Mandatory forms");
  lines.push("");
  for (const f of state.forms) lines.push(`- ${f.id} ${f.name.en} — ${f.status.replace(/_/g, " ")} (${f.owner})`);
  lines.push("");
  lines.push(`_Generated by NARVO Bid & Proposal Intelligence · ${new Date().toISOString().slice(0, 16).replace("T", " ")}_`);
  return lines.join("\n");
}

export function download(name: string, text: string, type = "text/markdown;charset=utf-8") {
  const blob = new Blob([text], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
